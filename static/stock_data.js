// Standard lookup helper
window.getStockProfile = function(symbol) {
  if (!symbol) return null;
  const sym = symbol.toUpperCase().trim();
  if (window.STOCK_MARKET_DATABASE[sym]) {
    return window.STOCK_MARKET_DATABASE[sym];
  }
  // Check without exchange suffix
  const cleanSym = sym.split('.')[0];
  if (window.STOCK_MARKET_DATABASE[cleanSym]) {
    return window.STOCK_MARKET_DATABASE[cleanSym];
  }
  return null;
};
